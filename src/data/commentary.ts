export function fill(text: string, vars: Record<string, string | number>): string {
  return text.replace(/\{([^}]+)\}/g, (m, k: string) => (vars[k] !== undefined ? String(vars[k]) : m));
}

/** Lines used lately per pool, so a line comes back only after most of its pool was heard. */
const recentLines = new Map<string, string[]>();

/** Picks a line from a pool, skipping the ones heard most recently in that pool. */
export function freshLine(pool: string, lines: string[]): string {
  const recent = recentLines.get(pool) ?? [];
  const fresh = lines.filter((l) => !recent.includes(l));
  const options = fresh.length > 0 ? fresh : lines;
  const line = options[Math.floor(Math.random() * options.length)];
  const keep = Math.max(0, Math.ceil(lines.length * 0.7) - 1);
  recentLines.set(pool, [line, ...recent.filter((l) => l !== line)].slice(0, keep));
  return line;
}
